"""Generate the finite typing catalogue from real Bilt dimension arithmetic.

Run with PYTHONPATH=src. --check verifies committed output. Custom dimensions
are included in this project's catalogue; this does not extend installed stubs.
"""

from pathlib import Path
import argparse
from bilt.units import dimensions as dims

ROOT = Path(__file__).parent / "bilt_typing"
CATALOGUE = {
    "MASS": (dims.MASS, "Mass"),
    "LENGTH": (dims.LENGTH, "Length"),
    "TIME": (dims.TIME, "Duration"),
    "AREA": (dims.AREA, "Area"),
    "VOLUME": (dims.VOLUME, "Volume"),
    "ACCELERATION": (dims.LENGTH / dims.TIME**2, "Acceleration"),
    "FORCE": (dims.FORCE, "Force"),
    "DIMENSIONLESS": (dims.DIMENSIONLESS, "Dimensionless"),
    "TEMPERATURE": (dims.TEMPERATURE, "Temperature"),
    # Example project extension: edit this catalogue, regenerate the whole layer.
    "MASS_PER_LENGTH": (dims.MASS / dims.LENGTH, "MassPerLength"),
}
UNIT_NAMES = {
    "kilogram": "MASS",
    "gram": "MASS",
    "meter": "LENGTH",
    "second": "TIME",
    "newton": "FORCE",
    "kelvin": "TEMPERATURE",
    "absolute_celsius": "ABSOLUTE_TEMPERATURE",
    "absolute_fahrenheit": "ABSOLUTE_TEMPERATURE",
}
REPS = [
    ("float", "float", "float"),
    ("float", "Tensor[float]", "Tensor[float]"),
    ("Tensor[float]", "float", "Tensor[float]"),
    ("Tensor[float]", "Tensor[float]", "Tensor[float]"),
]


def generate():
    header = "# Generated by ../generate.py; do not edit.\n"
    out = [
        header,
        "from bilt.units import Dimension\nfrom bilt.units._category import UnitCategory\nfrom ._markers import DimensionType\n",
    ]
    canonical = {}
    for name, (dimension, _) in CATALOGUE.items():
        if dimension in canonical:
            out.append(f"type {name} = {canonical[dimension]}\n")
        else:
            canonical[dimension] = name
            out.append(f"class {name}(DimensionType):\n    runtime = {dimension!r}\n")
    out.append("class ABSOLUTE_TEMPERATURE(DimensionType):\n    runtime = TEMPERATURE.runtime\n    absolute = True\n")
    out.append(
        "REGISTRY = {\n"
        + "".join(f"    ({n}.runtime, False): {n},\n" for n in canonical.values())
        + "    (ABSOLUTE_TEMPERATURE.runtime, True): ABSOLUTE_TEMPERATURE,\n}\n"
    )
    out.append(
        'def marker_for(unit):\n    key = (unit.dimension, unit.category is UnitCategory.ABSOLUTE)\n    if key not in REGISTRY:\n        raise TypeError(f"Dimension outside prototype catalogue: {unit.dimension}")\n    return REGISTRY[key]\n'
    )
    files = {"dimension_types.py": "\n".join(out)}
    aliases = [
        header,
        "from . import dimension_types as dt\nfrom ._values import Quantity, Tensor\n\ntype Float = float | Tensor[float]\n",
    ]
    for name, (_, alias) in CATALOGUE.items():
        aliases.append(f"type {alias}[R: Float] = Quantity[dt.{name}, R]\n")
    aliases.append("type AbsoluteTemperature[R: Float] = Quantity[dt.ABSOLUTE_TEMPERATURE, R]\n")
    files["quantities.py"] = "".join(aliases)
    units = [
        header,
        "from bilt import units as runtime\nfrom . import dimension_types as dt\nfrom ._values import Unit\n",
    ]
    for name, dim in UNIT_NAMES.items():
        units.append(f"{name}: Unit[dt.{dim}] = Unit(runtime.{name}, dt.{dim})\n")
    units.append(
        "meter_per_second_squared: Unit[dt.ACCELERATION] = Unit(runtime.meter / runtime.second**2, dt.ACCELERATION)\n"
    )
    units.append(
        "kilogram_per_meter: Unit[dt.MASS_PER_LENGTH] = Unit(runtime.kilogram / runtime.meter, dt.MASS_PER_LENGTH)\n"
    )
    files["units.py"] = "".join(units)
    stub = [
        header,
        """from typing import Generic, TypeVar, overload
import numpy as np
from numpy.typing import NDArray
from bilt import Dim
from bilt.symbolic._domains import Domain
from bilt.units import Unit as NativeUnit
from ._markers import DimensionType
from . import dimension_types as dt

D = TypeVar("D", bound=DimensionType)
R = TypeVar("R", bound=float | Tensor[float])
T = TypeVar("T")
class Tensor(Generic[T]):
    values: NDArray[np.float64]
    domain: Domain
    def __init__(self, values: NDArray[np.float64], domain: Domain) -> None: ...
class Unit(Generic[D]):
    runtime: NativeUnit
    dimension: type[D]
    def __init__(self, runtime: NativeUnit, dimension: type[D]) -> None: ...
    def __rmul__(self, value: float) -> Quantity[D, float]: ...
class Quantity(Generic[D, R]):
    value: R
    unit: Unit[D]
    def __init__(self, value: R, unit: Unit[D]) -> None: ...
    def convert_to(self, unit: Unit[D]) -> Quantity[D, R]: ...
    def __eq__(self, other: object) -> bool: ...
    def __rmul__(self, other: float) -> Quantity[D, R]: ...
    def sum(self: Quantity[D, Tensor[float]], axis: Dim) -> Quantity[D, float | Tensor[float]]: ...
""",
    ]
    for left, right, result in REPS:
        stub.append(
            f"    @overload\n    def __add__(self: Quantity[D, {left}], other: Quantity[D, {right}]) -> Quantity[D, {result}]: ...\n"
        )
    for operator, runtime_op in [("__mul__", lambda a, b: a * b), ("__truediv__", lambda a, b: a / b)]:
        stub.append(f"    @overload\n    def {operator}(self, other: float) -> Quantity[D, R]: ...\n")
        for ln, (ld, _) in CATALOGUE.items():
            for rn, (rd, _) in CATALOGUE.items():
                result_dim = canonical.get(runtime_op(ld, rd))
                if result_dim:
                    for lr, rr, result_rep in REPS:
                        stub.append(
                            f"    @overload\n    def {operator}(self: Quantity[dt.{ln}, {lr}], other: Quantity[dt.{rn}, {rr}]) -> Quantity[dt.{result_dim}, {result_rep}]: ...\n"
                        )
    stub.append("""def tensor(values: object, *, over: Dim | tuple[Dim, ...], unit: Unit[D]) -> Quantity[D, Tensor[float]]: ...
def to_native(value: object) -> object: ...
def from_native(value: object) -> object: ...
""")
    files["_values.pyi"] = "".join(stub)
    return files


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for name, content in generate().items():
        path = ROOT / name
        if args.check:
            if not path.exists() or path.read_text() != content:
                raise SystemExit(f"Generated file is stale: {path}")
        else:
            path.write_text(content)
