"""Contracts for named tensor expressions."""

import typing

from bilt.units._protocols import Quantity

if typing.TYPE_CHECKING:
    import numpy as np

    from bilt.symbolic._dimensions import Coordinate, Dim
    from bilt.symbolic._domains import Domain
    from bilt.units._units import Unit


class _Tensorial(typing.Protocol):
    """Shape-preserving carrier operations over named dimensions."""

    @property
    def values(self) -> np.ndarray: ...

    @property
    def domain(self) -> Domain: ...

    @property
    def shape(self) -> tuple[int, ...]: ...

    @property
    def ndim(self) -> int: ...

    def __float__(self) -> float: ...

    def sum(self, dim: Dim, /) -> typing.Self: ...

    def mean(self, dim: Dim, /) -> typing.Self: ...

    def min(self, dim: Dim, /) -> typing.Self: ...

    def max(self, dim: Dim, /) -> typing.Self: ...

    def prod(self, dim: Dim, /) -> typing.Self: ...

    def isel(self, dim: Dim, index: int, /) -> typing.Self: ...

    def sel(self, dim: Dim, coordinate: Coordinate, /) -> typing.Self: ...


@typing.runtime_checkable
class Tensor(_Tensorial, typing.Protocol):
    """A unitless tensor expression."""

    @property
    def unit(self) -> None: ...

    @property
    def _unitless_tensor_marker(self) -> typing.Literal[True]: ...

    def __add__(self, other: Tensor | float, /) -> Tensor: ...

    def __radd__(self, other: float, /) -> Tensor: ...

    def __sub__(self, other: Tensor | float, /) -> Tensor: ...

    def __rsub__(self, other: float, /) -> Tensor: ...

    @typing.overload
    def __mul__(self, other: Quantity | Unit, /) -> QuantityTensor: ...

    @typing.overload
    def __mul__(self, other: Tensor | float, /) -> Tensor: ...

    @typing.overload
    def __rmul__(self, other: Quantity | Unit, /) -> QuantityTensor: ...

    @typing.overload
    def __rmul__(self, other: float, /) -> Tensor: ...

    @typing.overload
    def __truediv__(self, other: Quantity, /) -> QuantityTensor: ...

    @typing.overload
    def __truediv__(self, other: Tensor | float, /) -> Tensor: ...

    @typing.overload
    def __rtruediv__(self, other: Quantity, /) -> QuantityTensor: ...

    @typing.overload
    def __rtruediv__(self, other: float, /) -> Tensor: ...

    def __pow__(self, other: float | Tensor, /) -> Tensor: ...

    def __rpow__(self, other: float, /) -> typing.Self: ...

    def __pos__(self) -> typing.Self: ...

    def __neg__(self) -> typing.Self: ...

    def __abs__(self) -> typing.Self: ...

    def __lt__(self, other: Tensor | float, /) -> bool: ...

    def __le__(self, other: Tensor | float, /) -> bool: ...

    def __gt__(self, other: Tensor | float, /) -> bool: ...

    def __ge__(self, other: Tensor | float, /) -> bool: ...


@typing.runtime_checkable
class QuantityTensor(Quantity, _Tensorial, typing.Protocol):
    """A dimensioned tensor expression."""

    @property
    def value(self) -> Tensor: ...

    def __add__(self, other: Quantity, /) -> QuantityTensor: ...

    def __sub__(self, other: Quantity, /) -> QuantityTensor: ...

    def __mul__(self, other: Quantity | Tensor | Unit | float, /) -> QuantityTensor: ...

    def __rmul__(self, other: Quantity | Tensor | Unit | float, /) -> QuantityTensor: ...

    def __truediv__(self, other: Quantity | Tensor | Unit | float, /) -> QuantityTensor: ...

    def __rtruediv__(self, other: Quantity | Tensor | float, /) -> QuantityTensor: ...

    def __pow__(self, other: Quantity | float, /) -> QuantityTensor: ...


Number = float | Tensor
