"""Typing contract for dimensioned scalar or tensor expressions.

These protocols describe symbolic model expressions, not general eager arithmetic.
Runtime port validation inspects the actual value and its unit.
"""

import typing

if typing.TYPE_CHECKING:
    from bilt.core._tensors._protocols import Number, QuantityTensor, Tensor
    from bilt.units._units import Unit


@typing.runtime_checkable
class Quantity(typing.Protocol):
    """A unit-bearing expression whose shape is not fixed."""

    @property
    def unit(self) -> Unit: ...

    @property
    def value(self) -> Number: ...

    def convert_to(self, unit: Unit, /) -> typing.Self: ...

    def cast_to(self, unit: Unit, /) -> typing.Self: ...

    def strip_metadata(self) -> typing.Self: ...

    @typing.overload
    def __add__(self, other: QuantityTensor, /) -> QuantityTensor: ...

    @typing.overload
    def __add__(self, other: Quantity, /) -> Quantity: ...

    @typing.overload
    def __sub__(self, other: QuantityTensor, /) -> QuantityTensor: ...

    @typing.overload
    def __sub__(self, other: Quantity, /) -> Quantity: ...

    @typing.overload
    def __mul__(self, other: QuantityTensor | Tensor, /) -> QuantityTensor: ...

    @typing.overload
    def __mul__(self, other: Quantity | Unit | float, /) -> Quantity: ...

    @typing.overload
    def __rmul__(self, other: QuantityTensor | Tensor, /) -> QuantityTensor: ...

    @typing.overload
    def __rmul__(self, other: Quantity | Unit | float, /) -> Quantity: ...

    @typing.overload
    def __truediv__(self, other: QuantityTensor | Tensor, /) -> QuantityTensor: ...

    @typing.overload
    def __truediv__(self, other: Quantity | Unit | float, /) -> Quantity: ...

    @typing.overload
    def __rtruediv__(self, other: QuantityTensor | Tensor, /) -> QuantityTensor: ...

    @typing.overload
    def __rtruediv__(self, other: Quantity | float, /) -> Quantity: ...

    @typing.overload
    def __pow__(self, other: QuantityTensor, /) -> QuantityTensor: ...

    @typing.overload
    def __pow__(self, other: Quantity | float, /) -> Quantity: ...

    def __pos__(self) -> typing.Self: ...

    def __neg__(self) -> typing.Self: ...

    def __abs__(self) -> typing.Self: ...

    def __lt__(self, other: Quantity, /) -> bool: ...

    def __le__(self, other: Quantity, /) -> bool: ...

    def __gt__(self, other: Quantity, /) -> bool: ...

    def __ge__(self, other: Quantity, /) -> bool: ...
